/**
 * Publishing — the bridge between "a provider uploaded a spec" and "a proxy
 * exists on the gateway".
 *
 * ## The Edge object graph behind one published API
 *
 * ```
 * apis row ─── proxy  name `nexus-<slug>`, listen_path `/<ns>/<slug>`
 *               │      allowed_methods, backend_*_timeout_ms, circuit_breaker,
 *               │      allowed_ws_origins — settings on the proxy itself
 *               │
 *               │  proxy.plugins[] ── the association list; this is what makes
 *               │                     a config run at all
 *               ├─ plugin_config    the auth plugin (key_auth | basic_auth | jwt_auth)
 *               ├─ plugin_config    access_control, only when `requestable`
 *               ├─ plugin_config    rate_limiting, only when a rate limit is set
 *               ├─ plugin_config    cors, only when a CORS policy is set
 *               ├─ plugin_config    openapi_validator, in `routes` mode — owned
 *               │                   with operation schemas generated by Edge
 *               └─ plugin_config    one per `api_plugins` row — the provider
 *                                   plugin palette, managed by
 *                                   `plugins/service.ts`
 * ```
 *
 * ## `routes` enforcement means a spec-owned proxy
 *
 * Edge refuses an `openapi_validator` on a proxy with no attached `api_spec`,
 * and only its spec importer sets that stamp. So an API in `routes` mode does
 * **not** get its proxy from `POST /proxies`: the whole proxy is created by
 * `POST /api-specs`, from the provider's own document with `servers` rewritten
 * to the listen path and `x-ferrum-proxy` / `x-ferrum-validate` stamped on
 * (`spec-document.ts`). Edge creates the proxy, generates the operation table
 * and associates the validator in one transaction.
 *
 * Three consequences run through everything below:
 *
 * - a spec revision on a `routes` API is a `PUT /api-specs/{id}`, not a plugin
 *   replace — and because that re-inserts the proxy from the submitted
 *   `x-ferrum-proxy`, the backend move rides along in the same call instead of
 *   in a separate `PUT /proxies/{id}`;
 * - `PUT /proxies/{id}` still works on a spec-owned proxy and leaves both the
 *   stamp and the association list alone, so every runtime-settings PATCH keeps
 *   going through `mutateProxy` exactly as before;
 * - **moving between the two modes rebuilds the proxy.** Edge has no way to
 *   attach a spec to an existing proxy or to detach one, and it refuses a spec
 *   naming a proxy id that already exists, so the conversion is a delete and a
 *   recreate under the same id, with every hand-owned plugin config put back.
 *   The API is unreachable for that handful of round trips; it is recorded in
 *   the audit row and documented in the provider guide.
 *
 * A CORS policy no longer touches the validator at all: `cors` runs at priority
 * 100 and `openapi_validator` at 2960, so the preflight is answered and
 * short-circuited long before the unknown-operation check.
 *
 * ## Two settings are not free-standing
 *
 * `allowed_methods` and `allowed_ws_origins` live on the proxy but are partly
 * *derived from the CORS policy*, because Edge evaluates them before, and
 * independently of, the `cors` plugin:
 *
 * - a method outside `allowed_methods` is `405`ed **before any plugin runs**,
 *   so the list written to the gateway carries `OPTIONS` whenever the API has a
 *   CORS policy, or every browser preflight would fail;
 * - the `cors` plugin does not run on a WebSocket upgrade at all, and an
 *   HTTP proxy on Edge accepts upgrades on the same listen path, so the CORS
 *   origins are mirrored into `allowed_ws_origins` unless the provider explicitly
 *   opts out of the CSWSH check with `cors.enforce_websocket_origins: false`.
 *
 * The `apis` row stores the provider's own method list and nothing for the WS
 * origins; both derivations are recomputed whenever either input changes.
 *
 * **A plugin config with a matching `proxy_id` is inert until the proxy's own
 * `plugins[]` names it.** Edge decides what to run in `plugin_cache.rs`
 * (`scoped_plugin_config_applies_to_proxy`): a proxy-scoped config applies only
 * when it targets the proxy *and* the proxy associates it. Creating the config
 * is therefore only half the job — every create is followed by an association
 * write, and every removal is preceded by a disassociation.
 *
 * Nexus stores the proxy id on the `apis` row and **does not** store the plugin
 * config ids: they are looked up with `GET /plugins/config` filtered by
 * `proxy_id` whenever they need changing. That keeps the schema free of ids
 * whose lifecycle Nexus does not own, and reconciles automatically if an
 * operator ever recreates one by hand.
 *
 * ## Every proxy write is read-modify-write
 *
 * `PUT /proxies/{id}` is a whole-resource replace against a struct carrying
 * `deny_unknown_fields`, with no concurrency token — the same shape as
 * `PUT /consumers/{id}`. A body built only from the fields Nexus models resets
 * everything it omits to its serde default, so an operator's `hosts`,
 * timeouts, backend TLS, `upstream_id` — and the association list itself —
 * would vanish the first time a provider moved an upstream. Every write
 * therefore goes through `mutateProxy`: `GET`, change the handful of fields
 * that are actually changing, `PUT` the whole document back, serialised per
 * proxy id so two concurrent round trips cannot lose one edit.
 *
 * That machinery — `mutateProxy`, `attach`, `associate`/`disassociate`, the
 * undo steps and `reconcileOptionalPlugin` — lives in
 * [edge-plugins.ts](./edge-plugins.ts), shared with the provider plugin palette
 * (`plugins/service.ts`) so both drive the gateway through one implementation
 * and, crucially, one per-proxy lock.
 *
 * **`PUT /api-specs/{id}` is a proxy write too.** It re-inserts the proxy from
 * the submitted `x-ferrum-proxy`, so it has the same lost-update shape as
 * `PUT /proxies/{id}` while wearing a different URL: the read that builds the
 * body, the replace and any compensation all have to happen under the *same*
 * `proxy:<id>` key, or a runtime `PATCH` landing in between is silently
 * discarded. Callers that need to compose several calls that way take the key
 * once with `binder.withProxy` and use the `…Locked` helpers inside — neither
 * the in-process queue nor the `edge_leases` row is re-entrant.
 *
 * ## Publishing is a multi-write sequence with no transaction
 *
 * Edge has no cross-resource transaction, so `publish` creates the proxy, then
 * each plugin config, and **rolls back what it created** if any step fails
 * (delete the plugin configs, then the proxy) before rethrowing. The Nexus rows
 * are written last but *inside* that same compensated block, in one store
 * transaction, so a store failure cannot leave a live proxy the portal has no
 * row for. `update` uses the same technique with an explicit undo stack, and
 * `updateSpec` moves the gateway before the revision becomes current.
 *
 * Where a step genuinely cannot be made atomic, the failure is arranged to land
 * in the safe direction and is documented at the call site: an API stays
 * reachable and authenticated rather than becoming open or orphaned.
 *
 * **An undo step is registered before the write it undoes, never after.** A
 * rejected Edge promise is not proof the write did not happen: a `PUT` the
 * gateway applied and could not acknowledge rejects exactly like one it
 * refused, and registering afterwards means the outer catch replays only the
 * *earlier* steps while the gateway keeps the change. Every read-modify-write
 * therefore hands its undo over from inside the mutator — after the `GET` that
 * produced the "before" snapshot, before the `PUT` — so the two cannot come
 * apart; `publish` mints its proxy id and records it before dispatching the
 * create for the same reason. The cost is an undo that sometimes replays a
 * write that never landed, which is a wasted idempotent call and nothing more,
 * and it is why every restore is scoped to the fields its own step wrote.
 *
 * **Compensation loops swallow, so a failed undo must be recorded.** A failing
 * request unwinds its stack best-effort — an undo step that threw must not
 * replace the failure the caller needs to see. What makes that safe is that
 * nothing is swallowed silently: the loop writes one
 * {@link AuditAction.API_GATEWAY_REPAIR_REQUIRED} row naming the proxy and the
 * steps that could not be replayed, and a step that can leave the gateway in a
 * state the portal does not describe *at all* — today only the
 * `spec_enforcement` rebuild, which deletes and recreates the proxy — writes
 * its own richer record before it throws and is excluded from the summary so
 * one incident is not reported twice. `publish` does the same with an
 * {@link AuditAction.API_PUBLISH_ROLLBACK} row, which names the proxy its
 * compensating delete could not confirm.
 *
 * Every such loop additionally **logs** what it swallowed, error message only —
 * the gateway is describable either way, but it may no longer describe what the
 * portal says, and the response the caller gets is about something else
 * entirely. `plugins/service.ts` follows the same rule for the palette's two
 * loops.
 *
 * ## The listen path moves last
 *
 * That sequence used to have one window it could not compensate for. Edge
 * serves a proxy the instant it is created, and the plugin configs attached
 * afterwards are inert until the association write — so the deterministic
 * `/<namespace>/<slug>` was live, open and unlimited for a handful of round
 * trips, and rollback could delete the proxy but not un-forward the requests.
 * Reordering does not help: Edge refuses a plugin config for a proxy that does
 * not exist, and `allowed_methods` must be `null` or a *non-empty* array, so
 * there is no deny-all proxy to create first.
 *
 * So the *path* moves instead. Every proxy Nexus creates is created on an
 * unguessable `/<namespace>/.staging/<128 bits>`
 * ({@link stagingListenPath}), gets its plugin configs attached and associated
 * there, and is moved onto the real path by
 * {@link cutOverToListenPath} as the **last gateway write** before the store
 * transaction. The final path is either a `404` or fully gated — never open.
 * The `spec_enforcement` conversion, which deletes and recreates the proxy,
 * takes the same detour for the same reason.
 *
 * ## Retirement versus deletion
 *
 * `status: 'retired'` is a *catalog* state, not a gateway state: the proxy and
 * its plugins stay exactly as they are, existing grants keep working, and the
 * API simply stops appearing in the catalog for anyone but its owner and
 * admins. That is deliberate — retiring an API must never silently break the
 * integrations already calling it. `DELETE /api/apis/:id` is the destructive
 * operation: it revokes every grant, tears the Edge objects down and removes
 * the rows.
 *
 * @see Edge `docs/admin_api.md`, "Proxies" and "Plugin Configs"; `access_control`
 *   and the other per-plugin `config` keys in Edge `docs/plugins.md`
 */

